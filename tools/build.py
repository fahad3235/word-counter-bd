#!/usr/bin/env python3
r"""Generate ASCII-safe js/i18n.js and js/data.js from tools/*-source.json.

Bengali is stored as \uXXXX escapes so every shipped file is pure ASCII
(GitHub push argv safety: non-ASCII argv corrupted Bengali in run #25).
Source of truth: tools/i18n-source.json and tools/data-source.json.
Run from the project root:  python3 tools/build.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load(name):
    with open(os.path.join(ROOT, 'tools', name), encoding='utf-8') as f:
        return json.load(f)

def dump_js(obj, varname, header):
    body = json.dumps(obj, ensure_ascii=True, indent=2, sort_keys=True)
    text = header + "'use strict';\nwindow." + varname + " = " + body + ";\n"
    assert all(ord(c) < 128 for c in text), 'non-ASCII leaked into generated JS'
    return text

i18n = load('i18n-source.json')
with open(os.path.join(ROOT, 'js', 'i18n.js'), 'w', encoding='ascii') as f:
    f.write(dump_js(i18n, 'I18N',
        '// GENERATED by tools/build.py from tools/i18n-source.json\n'
        '// Do not edit by hand. Bengali is stored as \\uXXXX escapes so this\n'
        '// file is pure ASCII (GitHub push argv safety). Source of truth:\n'
        '// tools/i18n-source.json\n'))

data = load('data-source.json')
with open(os.path.join(ROOT, 'js', 'data.js'), 'w', encoding='ascii') as f:
    f.write(dump_js(data, 'WC_DATA',
        '// GENERATED by tools/build.py from tools/data-source.json\n'
        '// Do not edit by hand. Bengali is stored as \\uXXXX escapes so this\n'
        '// file is pure ASCII (GitHub push argv safety). Source of truth:\n'
        '// tools/data-source.json\n'))

print('generated js/i18n.js (%d keys) and js/data.js' % len(i18n))
